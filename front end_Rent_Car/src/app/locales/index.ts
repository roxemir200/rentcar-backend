export type I18nLang = 'fr' | 'en' | 'ar';
export const I18N_LANGS: { code: I18nLang; label: string; flag: string; dir: 'ltr' | 'rtl' }[] = [
  { code: 'fr', label: 'Français', flag: '🇫🇷', dir: 'ltr' },
  { code: 'en', label: 'English',  flag: '🇬🇧', dir: 'ltr' },
  { code: 'ar', label: 'العربية',  flag: '🇹🇳', dir: 'rtl' },
];

// Applique la direction + langue sur <html>
export function applyDocumentLang(lang: I18nLang) {
  const def = I18N_LANGS.find(l => l.code === lang) ?? I18N_LANGS[0];
  try {
    document.documentElement.lang = def.code;
    document.documentElement.dir  = def.dir;
  } catch { /* SSR / noop */ }
}

i18n
  .use(LanguageDetector)
  .use(initReactI18next)
  .init({
    resources,
    fallbackLng: 'fr',
    supportedLngs: ['fr', 'en', 'ar'],
    ns: ['translation'],
    defaultNS: 'translation',
    interpolation: {
      escapeValue: false,
    },
    detection: {
      order: ['localStorage', 'navigator'],
      lookupLocalStorage: 'rentcar-lang', // compatibilité avec l'ancien stockage
      caches: ['localStorage'],
      cacheNonExistentLanguage: false,
    },
  })
  .then(() => {
    applyDocumentLang((i18n.resolvedLanguage as I18nLang) ?? 'fr');
  });

// Sync dès que la langue change par react-i18next (LanguageSwitcher)
i18n.on('languageChanged', (lng) => {
  const safeLang = (['fr', 'en', 'ar'].includes(lng) ? lng : 'fr') as I18nLang;
  applyDocumentLang(safeLang);
});

export default i18n;
